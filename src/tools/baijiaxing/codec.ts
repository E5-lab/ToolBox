/** 姓氏 → 索引 的反查表 */
const XING_INDEX: Map<string, number> = new Map();
BAI_JIA_XING.forEach((x, i) => {
  if (!XING_INDEX.has(x)) XING_INDEX.set(x, i);
});

/** 每 N 个姓氏插入一个分隔符，便于阅读 */
export type Separator = 'none' | 'space' | 'comma';

function sepChar(sep: Separator): string {
  if (sep === 'space') return ' ';
  if (sep === 'comma') return '，';
  return '';
}

/** 编码：文本 → 百家姓串 */
export function encode(text: string, sep: Separator = 'none'): string {
  if (!text) return '';
  const bytes = new TextEncoder().encode(text);
  const chars: string[] = [];
  for (const b of bytes) chars.push(BAI_JIA_XING[b]);
  return chars.join(sepChar(sep));
}

/** 解码：百家姓串 → 文本 */
export function decode(xing: string): string {
  if (!xing) return '';
  // 提取所有出现在码表中的姓氏字符（自动忽略标点、空格、换行等）
  const bytes: number[] = [];
  for (const ch of xing) {
    const idx = XING_INDEX.get(ch);
    if (idx !== undefined) bytes.push(idx);
  }
  if (bytes.length === 0) return '';
  return new TextDecoder().decode(new Uint8Array(bytes));
}
